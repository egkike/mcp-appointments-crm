// OQ-5: setup_staff.json specialties carry service NAMES; the seeder resolves
// them to the real service ids inserted in the same transaction. Fixture
// names are intentionally generic test names, never the B12 demo data.

func TestSeed_ResolvesSpecialtyNamesToIds(t *testing.T) {
	ctx := context.Background()
	conn := newTestDB(t)
	if _, err := isFreshDB(ctx, conn); err != nil {
		t.Fatalf("isFreshDB failed: %v", err)
	}
	data := mustLoadTestdata(t)
	data.Services = []SetupService{
		{Name: "Servicio A", DurationMinutes: 30, Price: 100, IsActive: 1},
		{Name: "Servicio B", DurationMinutes: 45, Price: 200, IsActive: 1},
	}
	data.Staff = []SetupStaffMember{
		{Name: "Profesional P", Status: "active", Specialties: []string{"Servicio A", "Servicio B"}},
	}
	// fix locales generated by tests
	for i := range data.Staff {
		data.Staff[i].Schedule = nil
	}

	if err := seed(ctx, conn, data); err != nil {
		t.Fatalf("seed failed: %v", err)
	}

	wantIDs := map[string]bool{}
	for _, svc := range data.Services {
		var gotID string
		if err := conn.QueryRowContext(ctx,
			"SELECT id FROM services WHERE name = ?", svc.Name).Scan(&gotID); err != nil {
			t.Fatalf("query service %q: %v", svc.Name, err)
		}
		wantIDs[gotID] = true
	}

	var specialties string
	if err := conn.QueryRowContext(ctx,
		"SELECT specialties FROM professionals WHERE name = ?", data.Staff[0].Name).Scan(&specialties); err != nil {
		t.Fatalf("query specialties: %v", err)
	}
	got := unmarshalStrArray(t, specialties)
	if len(got) != len(data.Services) {
		t.Errorf("specialties length = %d, want %d", len(got), len(data.Services))
	}
	for i, gotID := range got {
		if !wantIDs[gotID] {
			t.Errorf("specialties[%d] = %q, is not the id of any seeded service", i, gotID)
		}
		if i >= 1 && gotID == got[i-1] {
			t.Errorf("specialties[%d] duplicates %q", i, gotID)
		}
	}
}

func unmarshalStrArray(t *testing.T, raw string) []string {
	t.Helper()
	var got []string
	if err := json.Unmarshal([]byte(raw), &got); err != nil {
		t.Fatalf("unmarshal specialties %q: %v", raw, err)
	}
	return got
}

func TestSeed_UnknownSpecialtyNameAbortsSemantically(t *testing.T) {
	ctx := context.Background()
	conn := newTestDB(t)
	if _, err := isFreshDB(ctx, conn); err != nil {
		t.Fatalf("isFreshDB failed: %v", err)
	}
	data := mustLoadTestdata(t)
	data.Services = []SetupService{{Name: "Servicio A", DurationMinutes: 30, Price: 100, IsActive: 1}}
	data.Staff = []SetupStaffMember{{
		Name:        "Profesional P",
		Status:      "active",
		Specialties: []string{"Servicio Inexistente"},
	}}

	err := seed(ctx, conn, data)
	if err == nil {
		t.Fatal("expected error for unknown specialty name, got nil")
	}
	msg := err.Error()
	for _, want := range []string{"Profesional P", "Servicio Inexistente", "Servicio A"} {
		if !contains(msg, want) {
			t.Errorf("error %q missing %q", msg, want)
		}
	}

	// Full rollback: nothing seeded, DB stays fresh.
	var profCount, svcCount int
	if err := conn.QueryRowContext(ctx, "SELECT COUNT(*) FROM professionals").Scan(&profCount); err != nil {
		t.Fatalf("count professionals after rollback: %v", err)
	}
	if profCount != 0 {
		t.Errorf("professionals count after rollback = %d, want 0", profCount)
	}
	if err := conn.QueryRowContext(ctx, "SELECT COUNT(*) FROM services").Scan(&svcCount); err != nil {
		t.Fatalf("count services after rollback: %v", err)
	}
	if svcCount != 0 {
		t.Errorf("services count after rollback = %d, want 0", svcCount)
	}
	var name string
	if err := conn.QueryRowContext(ctx,
		"SELECT name FROM business_profile WHERE id = 'singleton'").Scan(&name); err != nil {
		t.Fatalf("query business_profile after rollback: %v", err)
	}
	if name != "" {
		t.Errorf("business_profile.name = %q, want empty after rollback", name)
	}
}

func TestSeed_LegacyEmptySpecialtiesImportsClean(t *testing.T) {
	ctx := context.Background()
	conn := newTestDB(t)
	if _, err := isFreshDB(ctx, conn); err != nil {
		t.Fatalf("isFreshDB failed: %v", err)
	}
	data := mustLoadTestdata(t)
	data.Staff[0].Specialties = []string{}

	if err := seed(ctx, conn, data); err != nil {
		t.Fatalf("seed failed: %v", err)
	}
	var specialties string
	if err := conn.QueryRowContext(ctx,
		"SELECT specialties FROM professionals WHERE name = ?", data.Staff[0].Name).Scan(&specialties); err != nil {
		t.Fatalf("query specialties: %v", err)
	}
	if specialties != "[]" {
		t.Errorf("specialties = %q, want []", specialties)
	}
}

func contains(s, sub string) bool {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return true
		}
	}
	return false
}
